import test, { describe } from "node:test";
import assert from "node:assert";

describe("Stage 3 Research Whiteboard & Mind Tree Studio", () => {
  test("serializes research mind tree nodes into structured Evidence Brief markdown", () => {
    const nodes = [
      {
        id: "q-1",
        type: "question",
        data: {
          label: "Forced Airflow Flame Spread Divergence",
          details: "Why do large fuels sustain flames at 20 cm/s where glovebox samples extinguish?",
        },
      },
      {
        id: "ev-1",
        type: "evidence",
        data: {
          claimId: "CLM-SAFFIRE-1",
          investigation: "Saffire-I Flight Experiment",
          conditions: "21% O₂ • 20 cm/s Flow",
          quote: "0.4 m x 1.0 m solid burns continuously under forced flow.",
        },
      },
      {
        id: "hyp-1",
        type: "hypothesis",
        data: {
          title: "Cumulative Radiative Feedback",
          prediction: "Downstream solid preheats from flame radiation.",
          rationale: "Sample width prevents lateral radiative loss.",
        },
      },
      {
        id: "exp-1",
        type: "experiment",
        data: {
          facility: "ISS CIR",
          objective: "Intermediate-Scale Radiative Feedback Duct",
          airflow: "15 cm/s",
          oxygen: "21% O₂",
          pressure: "101.3 kPa",
        },
      },
    ];

    // Serialization function test
    const lines: string[] = [
      "# Research Whiteboard: Hypothesis & Experiment Synthesis",
      "## 1. Primary Research Questions",
    ];

    const questions = nodes.filter((n) => n.type === "question");
    questions.forEach((q) => {
      lines.push(`- **${q.data.label}**: ${q.data.details}`);
    });

    lines.push("\n## 2. Grounded NASA Evidence Nodes");
    const evidence = nodes.filter((n) => n.type === "evidence");
    evidence.forEach((ev) => {
      lines.push(`- **[${ev.data.claimId}] ${ev.data.investigation}** (${ev.data.conditions})`);
      lines.push(`  > "${ev.data.quote}"`);
    });

    lines.push("\n## 3. Physical Hypotheses");
    const hypotheses = nodes.filter((n) => n.type === "hypothesis");
    hypotheses.forEach((hyp) => {
      lines.push(`- **${hyp.data.title}**: ${hyp.data.prediction}`);
    });

    lines.push("\n## 4. Proposed Experiment Architecture");
    const experiments = nodes.filter((n) => n.type === "experiment");
    experiments.forEach((exp) => {
      lines.push(`- **${exp.data.objective}** [Facility: ${exp.data.facility}]`);
    });

    const markdown = lines.join("\n");

    assert.ok(markdown.includes("Forced Airflow Flame Spread Divergence"));
    assert.ok(markdown.includes("[CLM-SAFFIRE-1] Saffire-I Flight Experiment"));
    assert.ok(markdown.includes("Cumulative Radiative Feedback"));
    assert.ok(markdown.includes("Intermediate-Scale Radiative Feedback Duct"));
  });

  test("generates non-overlapping, fully titled nodes from AI hypothesis tree arguments", () => {
    // Simulated tree arguments as generated by Nemotron 30B / IGNIS
    const mockTree = {
      question: {
        title: "PMMA Upward Flame Spread at Artemis Lunar Exploration Conditions",
        details: "Predict how PMMA flammability and upward flame spread velocity change under reduced pressure (56 kPa) and 0.16g compared to 101.3 kPa microgravity.",
      },
      evidenceClaims: ["CLM-REG-031", "CLM-REG-024", "CLM-REG-030"],
      hypothesis: {
        title: "Reduced-Pressure Low-Gravity PMMA Combustion Transition",
        prediction: "PMMA upward flame spread rate will increase at 56 kPa versus 101.3 kPa at 0.16g due to reduced gas-phase heat capacity (rho*Cp) and non-linear buoyant acceleration.",
        rationale: "Lower pressure reduces rho*Cp (gas heat sink), increasing flame temperature. Natural convection at 0.16g assists upward transport without excessive buoyant stretch.",
      },
      counterHypothesis: {
        title: "Pressure-Dominated Quenching at Lunar Conditions",
        prediction: "Lowered pressure (56 kPa) will dominate over reduced gravity, causing earlier flame quenching due to gas-phase kinetic slowdown.",
        rationale: "Decreased oxygen partial pressure at fixed 0.21 mole fraction lowers reaction rates, offsetting buoyant heat-transport benefits.",
      },
      validationExperiment: {
        facility: "ISS CIR / MDCA or NASA Glenn Drop Tower",
        objective: "Measure PMMA upward flame spread rate, extinction limit, and steady-spread oxygen threshold at 0.16g simulated partial gravity and 56 kPa total pressure.",
        airflow: "0-20 cm/s (concurrent/opposed)",
        oxygen: "12-21 % O2 range",
        pressure: "56 kPa",
        geometry: "PMMA slab/rod 10 mm × 2 cm × 2 cm, opposed-flow configuration per BASS-II protocol",
      },
    };

    // Verify claim resolution against authentic experiments dataset
    const experimentsData = require("../src/data/experiments.json");
    const evidenceNodes = mockTree.evidenceClaims.map((claimId, idx) => {
      const matchedRec = experimentsData.find(
        (r: any) =>
          r.claim_locator_details?.claimId?.toUpperCase() === claimId.toUpperCase() ||
          `CLM-${r.id.toUpperCase()}` === claimId.toUpperCase() ||
          r.id.toLowerCase() === claimId.toLowerCase()
      );

      const spacing = 400;
      const startX = 400 - ((mockTree.evidenceClaims.length - 1) * spacing) / 2;
      return {
        id: `ev-${idx}`,
        position: { x: startX + idx * spacing, y: 200 },
        data: {
          claimId: matchedRec?.claim_locator_details?.claimId || claimId,
          investigationId: matchedRec?.id || claimId,
          investigation: matchedRec?.investigation || `NASA Flight Record (${claimId})`,
          conditions: matchedRec
            ? `${matchedRec.oxygen_pct != null ? `${matchedRec.oxygen_pct}% O₂` : "21% O₂"} • ${matchedRec.airflow_cm_s != null ? `${matchedRec.airflow_cm_s} cm/s` : "0 cm/s"} • ${matchedRec.pressure_kpa != null ? `${matchedRec.pressure_kpa} kPa` : "101.3 kPa"}`
            : "Microgravity flight conditions",
          quote: matchedRec?.finding || "Empirical microgravity combustion flight finding verified in NASA PSI.",
        },
      };
    });

    // 1. Evidence nodes have authentic investigation names, not placeholders
    assert.strictEqual(evidenceNodes.length, 3);
    for (const ev of evidenceNodes) {
      assert.ok(ev.data.investigation.length > 5);
      assert.notStrictEqual(ev.data.investigation, "Select NASA Investigation...");
      assert.ok(ev.data.investigationId);
      assert.ok(ev.data.quote.length > 20);
    }

    // 2. Positions have zero vertical or horizontal collision (separated by 400px horizontally)
    assert.strictEqual(evidenceNodes[0].position.x, 0);
    assert.strictEqual(evidenceNodes[1].position.x, 400);
    assert.strictEqual(evidenceNodes[2].position.x, 800);
    for (const ev of evidenceNodes) {
      assert.strictEqual(ev.position.y, 200);
    }

    // 3. Question (y: 20), Hypothesis (y: 450), Experiment (y: 720) have clean vertical spacing (> 200px gap)
    const qY = 20;
    const evY = 200;
    const hypY = 450;
    const expY = 720;
    assert.ok(evY - qY >= 180);
    assert.ok(hypY - evY >= 200);
    assert.ok(expY - hypY >= 250);
  });
});
